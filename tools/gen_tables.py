#!/usr/bin/env python3
"""Generate src/tables.rs: the tables behind Python's html.unescape and the Unicode decimal digits.

The crate decodes HTML character references and reads digits exactly like Python does, so the tables are copied
from the Python standard library instead of from another source. Run from the crate root:

    python3 tools/gen_tables.py > src/tables.rs
"""
import html
import html.entities
import sys
import unicodedata


def rs(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % o)
    return '"' + "".join(out) + '"'


def main() -> None:
    w = sys.stdout.write
    w("// @generated by tools/gen_tables.py from the Python %s standard library. Do not edit.\n" % sys.version.split()[0])
    w("// HTML5 named character references (html.entities.html5), the numeric references HTML maps to other\n")
    w("// characters (html._invalid_charrefs), the code points html.unescape drops (html._invalid_codepoints) and the\n")
    w("// first code point of every run of Unicode decimal digits (category Nd, Unicode %s).\n\n" % unicodedata.unidata_version)
    ents = sorted(html.entities.html5.items(), key=lambda kv: kv[0].encode("utf-8"))
    w("/// `(name, replacement)`, sorted by name (byte order) for binary search.\n")
    w("pub(crate) static HTML5: [(&str, &str); %d] = [\n" % len(ents))
    for k, v in ents:
        w("    (%s, %s),\n" % (rs(k), rs(v)))
    w("];\n\n")
    inv = sorted(html._invalid_charrefs.items())
    w("/// Numeric character references that HTML maps to another character, sorted.\n")
    w("pub(crate) static INVALID_CHARREFS: [(u32, char); %d] = [\n" % len(inv))
    for k, v in inv:
        w("    (0x%x, '\\u{%x}'),\n" % (k, ord(v)))
    w("];\n\n")
    cps = sorted(html._invalid_codepoints)
    w("/// Code points that html.unescape replaces with nothing, sorted.\n")
    w("pub(crate) static INVALID_CODEPOINTS: [u32; %d] = [\n" % len(cps))
    for i in range(0, len(cps), 8):
        w("    " + ", ".join("0x%x" % c for c in cps[i:i + 8]) + ",\n")
    w("];\n\n")
    zeros = [c for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0]
    for z in zeros:  # every run is ten consecutive digits 0..9
        assert all(unicodedata.decimal(chr(z + i), None) == i for i in range(10)), hex(z)
    assert sum(1 for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd") == 10 * len(zeros)
    w("/// First code point (digit zero) of each run of ten Unicode decimal digits, sorted.\n")
    w("pub(crate) static DIGIT_ZEROS: [u32; %d] = [\n" % len(zeros))
    for i in range(0, len(zeros), 8):
        w("    " + ", ".join("0x%x" % c for c in zeros[i:i + 8]) + ",\n")
    w("];\n")


if __name__ == "__main__":
    main()
